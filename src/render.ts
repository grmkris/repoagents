// `.mcp.json` (Claude Code's shape, read natively by Claude and Grok) rendered for Codex (`.codex/config.toml`)
// and Cursor (`.cursor/mcp.json`). Pure functions; validateServers rejects what one of the targets cannot express.
import type { McpServer } from './schema.ts'

const WHOLE_VAR = /^\$\{([A-Za-z_][A-Za-z0-9_]*)\}$/u
const BEARER_VAR = /^Bearer \$\{([A-Za-z_][A-Za-z0-9_]*)\}$/u
const ANY_VAR = /\$\{([^}]*)\}/gu
const SECRETISH = /authorization|token|secret|key|password|cookie/iu

const GENERATED_PREFIX = '# GENERATED by repoagents'
const LEGACY_PREFIX = '# GENERATED by agents-sync'

/** Codex/TOML files repoagents (or its predecessor agents-sync) wrote and may overwrite. */
export const isGenerated = (text: string): boolean =>
  text.startsWith(GENERATED_PREFIX) || text.startsWith(LEGACY_PREFIX)

type Kind = 'stdio' | 'http' | 'sse'
const kindOf = (s: McpServer): Kind => s.type ?? (s.command === undefined ? 'http' : 'stdio')

const varProblems = (name: string, s: McpServer): string[] =>
  [...Object.values(s.headers ?? {}), ...Object.values(s.env ?? {}), ...(s.args ?? [])].flatMap((v) =>
    [...v.matchAll(ANY_VAR)]
      .filter((m) => m[1]?.includes(':-') === true)
      .map(() => `${name}: \${VAR:-default} cannot be expressed for Codex/Cursor`),
  )

const headerProblems = (name: string, s: McpServer): string[] =>
  Object.entries(s.headers ?? {}).flatMap(([h, v]) => [
    ...(SECRETISH.test(h) && !v.includes('${') ? [`${name}: header ${h} has an inline secret; use \${VAR}`] : []),
    ...(v.includes('${') && !WHOLE_VAR.test(v) && !BEARER_VAR.test(v)
      ? [`${name}: header ${h} must be exactly \${VAR} or "Bearer \${VAR}" for Codex`]
      : []),
  ])

const envProblems = (name: string, s: McpServer): string[] =>
  Object.entries(s.env ?? {})
    .filter(([k, v]) => SECRETISH.test(k) && !v.includes('${'))
    .map(([k]) => `${name}: env ${k} has an inline secret; use \${${k}}`)

const shapeProblems = (name: string, s: McpServer): string[] => {
  const kind = kindOf(s)
  return [
    ...(kind === 'sse' ? [`${name}: type "sse" is not supported by Codex; use streamable http`] : []),
    ...(kind !== 'stdio' && s.url === undefined ? [`${name}: http server needs url`] : []),
    ...(kind === 'stdio' && s.command === undefined ? [`${name}: stdio server needs command`] : []),
    ...(s.url?.includes('${') === true ? [`${name}: \${VAR} inside url cannot be expressed for Codex`] : []),
  ]
}

/** Problems that make a server unsafe or unportable, all of them (so `check` can list everything). */
export const validateServers = (servers: Readonly<Record<string, McpServer>>): string[] =>
  Object.entries(servers).flatMap(([name, s]) => [
    ...shapeProblems(name, s),
    ...varProblems(name, s),
    ...headerProblems(name, s),
    ...envProblems(name, s),
  ])

const tomlKey = (k: string): string => (/^[A-Za-z0-9_-]+$/u.test(k) ? k : JSON.stringify(k))
const tomlInline = (obj: Readonly<Record<string, string>>): string =>
  `{ ${Object.entries(obj)
    .map(([k, v]) => `${tomlKey(k)} = ${JSON.stringify(v)}`)
    .join(', ')} }`

const codexStdio = (s: McpServer): string[] => {
  const literal: Record<string, string> = {}
  const forwarded: string[] = []
  for (const [k, v] of Object.entries(s.env ?? {})) {
    if (WHOLE_VAR.exec(v)?.[1] === k) forwarded.push(k)
    else literal[k] = v
  }
  return [
    `command = ${JSON.stringify(s.command)}`,
    ...(s.args?.length ? [`args = [${s.args.map((a) => JSON.stringify(a)).join(', ')}]`] : []),
    ...(Object.keys(literal).length ? [`env = ${tomlInline(literal)}`] : []),
    ...(forwarded.length ? [`env_vars = [${forwarded.map((k) => JSON.stringify(k)).join(', ')}]`] : []),
  ]
}

const codexHttp = (s: McpServer): string[] => {
  const out = [`url = ${JSON.stringify(s.url)}`]
  const fromEnv: Record<string, string> = {}
  const literal: Record<string, string> = {}
  for (const [h, v] of Object.entries(s.headers ?? {})) {
    const bearer = BEARER_VAR.exec(v)?.[1]
    const whole = WHOLE_VAR.exec(v)?.[1]
    if (bearer !== undefined && h.toLowerCase() === 'authorization')
      out.push(`bearer_token_env_var = ${JSON.stringify(bearer)}`)
    else if (whole === undefined) literal[h] = v
    else fromEnv[h] = whole
  }
  if (Object.keys(literal).length) out.push(`http_headers = ${tomlInline(literal)}`)
  if (Object.keys(fromEnv).length) out.push(`env_http_headers = ${tomlInline(fromEnv)}`)
  return out
}

/**
 * Codex TOML. Every server is written as a full entry: Codex merges a project file field by field over the
 * user's global config, so a partial entry would inherit (or miss) fields from the machine.
 */
export const renderCodex = (servers: Readonly<Record<string, McpServer>>, version: string): string =>
  [
    `${GENERATED_PREFIX} v${version} from .mcp.json — edit .mcp.json, then re-run repoagents`,
    '',
    ...Object.entries(servers).flatMap(([name, s]) => [
      `[mcp_servers.${tomlKey(name)}]`,
      ...(kindOf(s) === 'stdio' ? codexStdio(s) : codexHttp(s)),
      '',
    ]),
  ].join('\n')

const toCursorVars = (v: string): string => v.replaceAll(ANY_VAR, (_, name: string) => `\${env:${name}}`)
const mapValues = (o: Readonly<Record<string, string>>): Record<string, string> =>
  Object.fromEntries(Object.entries(o).map(([k, v]) => [k, toCursorVars(v)]))

/** Cursor JSON: `${VAR}` becomes `${env:VAR}`. */
export const renderCursor = (servers: Readonly<Record<string, McpServer>>): string => {
  const mcpServers = Object.fromEntries(
    Object.entries(servers).map(([name, s]) => [
      name,
      kindOf(s) === 'stdio'
        ? {
            command: s.command,
            ...(s.args?.length ? { args: s.args.map(toCursorVars) } : {}),
            ...(s.env ? { env: mapValues(s.env) } : {}),
          }
        : { url: s.url, ...(s.headers ? { headers: mapValues(s.headers) } : {}) },
    ]),
  )
  return `${JSON.stringify({ mcpServers }, null, 2)}\n`
}
