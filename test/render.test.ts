import { describe, expect, it } from '@effect/vitest'
import { isGenerated, renderCodex, renderCursor, validateServers } from '../src/render.ts'

const servers = {
  myplan: { type: 'http' as const, url: 'https://myplan.lol/mcp' },
  api: {
    type: 'http' as const,
    url: 'https://x.dev/mcp',
    headers: { Authorization: 'Bearer ${API_TOKEN}', 'X-Team': '${TEAM}' },
  },
  local: { command: 'bunx', args: ['shadcn@4', 'mcp'], env: { DEBUG: '1', FOO_KEY: '${FOO_KEY}' } },
}

describe('render', () => {
  it('codex maps auth headers and env vars, one full entry per server', () => {
    const toml = renderCodex(servers, '1.2.3')
    expect(isGenerated(toml)).toBe(true)
    expect(toml).toContain('[mcp_servers.myplan]\nurl = "https://myplan.lol/mcp"')
    expect(toml).toContain('bearer_token_env_var = "API_TOKEN"')
    expect(toml).toContain('env_http_headers = { X-Team = "TEAM" }')
    expect(toml).toContain('args = ["shadcn@4", "mcp"]')
    expect(toml).toContain('env = { DEBUG = "1" }')
    expect(toml).toContain('env_vars = ["FOO_KEY"]')
  })

  it('cursor rewrites ${VAR} to ${env:VAR}', () => {
    const parsed: unknown = JSON.parse(renderCursor(servers))
    expect(parsed).toMatchObject({
      mcpServers: {
        myplan: { url: 'https://myplan.lol/mcp' },
        api: { headers: { Authorization: 'Bearer ${env:API_TOKEN}' } },
        local: { env: { FOO_KEY: '${env:FOO_KEY}' } },
      },
    })
  })

  it('rejects inline secrets, sse and ${VAR:-default}', () => {
    const errors = validateServers({
      a: { url: 'https://a/mcp', headers: { Authorization: 'Bearer abc123' } },
      b: { type: 'sse', url: 'https://b/sse' },
      c: { command: 'x', env: { T: '${T:-x}' } },
    })
    expect(errors.some((e) => e.includes('inline secret'))).toBe(true)
    expect(errors.some((e) => e.includes('sse'))).toBe(true)
    expect(errors.some((e) => e.includes(':-default'))).toBe(true)
  })

  it('recognises files written by the predecessor agents-sync as generated', () => {
    expect(isGenerated('# GENERATED by agents-sync v2.0.1 from .mcp.json')).toBe(true)
    expect(isGenerated('[mcp_servers.x]')).toBe(false)
  })
})
